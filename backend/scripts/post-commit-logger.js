#!/usr/bin/env node
/**
 * VetCare Post-Commit Auto-Logger
 * ────────────────────────────────
 * Runs automatically after every `git commit`.
 * Appends a structured entry to memories/repo/auto-commit-log.md capturing:
 *   - Timestamp, commit hash, message
 *   - Files changed + categories affected (DEPLOY, DB, UI, i18n, etc.)
 *   - Whether memory files were updated in this commit
 *
 * Installed by: node backend/scripts/install-hooks.js
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const LOG_FILE = path.join(ROOT, 'memories', 'repo', 'auto-commit-log.md');

function git(cmd) {
  // windowsHide + piped stdio: this runs on EVERY commit; the default pops a console window.
  try { return execSync(`git ${cmd}`, { cwd: ROOT, encoding: 'utf8', stdio: 'pipe', windowsHide: true }).trim(); }
  catch { return ''; }
}

// Get commit info
const hash    = git('rev-parse --short HEAD');
const message = git('log -1 --pretty=%B').split('\n')[0].trim();
const author  = git('log -1 --pretty=%an');
const date    = new Date().toISOString().replace('T', ' ').substring(0, 16);

// Get changed files in this commit
const changedRaw = git('diff-tree --no-commit-id -r --name-only HEAD');
const changed = changedRaw ? changedRaw.split('\n').filter(Boolean) : [];

// Categorise changes
const categories = new Set();
for (const f of changed) {
  if (f.startsWith('backend/src/routes'))    categories.add('API');
  if (f.startsWith('backend/src/services'))  categories.add('SERVICE');
  if (f.startsWith('backend/src/utils'))     categories.add('UTILS');
  if (f.startsWith('backend/migrations'))    categories.add('MIGRATION');
  if (f.includes('database.ts'))             categories.add('DB');
  if (f.startsWith('docker/'))               categories.add('DB-SCHEMA');
  if (f.startsWith('frontend/src/pages'))    categories.add('UI');
  if (f.startsWith('frontend/src/components')) categories.add('UI');
  if (f.startsWith('frontend/src/context'))  categories.add('AUTH/PERM');
  if (f.startsWith('frontend/src/locales'))  categories.add('i18n');
  if (f.includes('vite.config'))             categories.add('BUILD');
  if (f.includes('render-build') || f.includes('render-start') || f.includes('render.yaml')) categories.add('DEPLOY');
  if (f.includes('package.json') || f.includes('package-lock')) categories.add('DEPS');
  if (f.startsWith('memories/'))             categories.add('MEMORY');
  if (f.startsWith('backend/scripts'))       categories.add('TOOLING');
  if (f.startsWith('.github'))               categories.add('CONFIG');
}

// Detect if memory was updated in this commit
const memoryUpdated = changed.some(f => f.startsWith('memories/'));

// Detect commit type from message prefix
let commitType = 'OTHER';
const msgLower = message.toLowerCase();
if (msgLower.startsWith('fix:'))    commitType = '🐛 FIX';
else if (msgLower.startsWith('feat:'))   commitType = '✨ FEAT';
else if (msgLower.startsWith('chore:'))  commitType = '🔧 CHORE';
else if (msgLower.startsWith('refactor:')) commitType = '♻️  REFACTOR';
else if (msgLower.startsWith('test:'))   commitType = '🧪 TEST';
else if (msgLower.startsWith('docs:'))   commitType = '📝 DOCS';
else if (msgLower.startsWith('perf:'))   commitType = '⚡ PERF';

const memoryStatus = memoryUpdated ? '✅ Memory updated' : '⚠️  Memory NOT updated in this commit';

// Build log entry
const fileList = changed.length > 0
  ? changed.slice(0, 20).map(f => `  - ${f}`).join('\n') + (changed.length > 20 ? `\n  - ... and ${changed.length - 20} more` : '')
  : '  (no files listed)';

const catList = categories.size > 0 ? [...categories].join(' · ') : 'MISC';

const entry = `
## ${date} · \`${hash}\` · ${commitType}

**Commit:** ${message}  
**Author:** ${author}  
**Categories:** ${catList}  
**Memory:** ${memoryStatus}

<details>
<summary>Files changed (${changed.length})</summary>

${fileList}

</details>

---
`;

// Ensure file exists with header
if (!fs.existsSync(LOG_FILE)) {
  fs.writeFileSync(LOG_FILE, `# VetCare Auto-Commit Log

> Auto-generated by post-commit hook. Every commit is recorded here.
> Agents: read this file to understand what changed recently.
> Format: date · hash · type | message | categories | memory-status

---
`, 'utf8');
}

fs.appendFileSync(LOG_FILE, entry, 'utf8');

// Print minimal output (post-commit hooks should be quiet)
const memFlag = memoryUpdated ? '\x1b[32m✓ memory\x1b[0m' : '\x1b[33m⚠ memory not updated\x1b[0m';
console.log(`\x1b[2m[auto-log] ${hash} → auto-commit-log.md (${catList}) ${memFlag}\x1b[0m`);
